class SpinLockField<E> extends MergeLimitRPad<E> {

    int state;
    static final VarHandle STATE = fieldOffset(SpinLockField.class, "state", int.class);


    public SpinLockField(int capacity) {
        super(capacity);
    }

    public boolean tryLock() {
        return (int) STATE.getAcquire(this) != 0 && (int) STATE.getAndAdd(this, 1) == 0;
    }

    public void release() {
        STATE.setRelease(this, 0);
    }
}

